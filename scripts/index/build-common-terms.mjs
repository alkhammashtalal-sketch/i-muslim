// Lists the search terms found in ≥ 5% of the indexed Arabic documents (ayat, al-Muyassar, al-Saadi) and writes
// worker/src/config/common-terms.ar.json. retrieve() drops these single words from keyword queries: they rank
// nothing and make D1 read thousands of rows. Lexicon phrases are not affected.
//   node scripts/index/build-common-terms.mjs
import fs from 'node:fs';
import path from 'node:path';
import { ftsIndexText, stripTags } from '../../worker/src/lib/normalize.ts';

const ROOT = path.resolve(import.meta.dirname, '../..');
const THRESHOLD = 0.05;
const quran = fs
  .readFileSync(path.join(ROOT, 'data/processed/quran.jsonl'), 'utf8')
  .trim()
  .split('\n')
  .map((l) => JSON.parse(l));
const docs = quran.flatMap((r) => [r.text, r.muyassar, stripTags(r.saadi ?? '')]).filter(Boolean);
const df = new Map();
for (const d of docs) for (const t of new Set(ftsIndexText(d).split(' '))) df.set(t, (df.get(t) ?? 0) + 1);
const terms = [...df.entries()]
  .filter(([, c]) => c / docs.length >= THRESHOLD)
  .sort((a, b) => b[1] - a[1])
  .map(([t]) => t);
const out = {
  _about: `Generated by scripts/index/build-common-terms.mjs: terms in at least ${THRESHOLD * 100}% of ${docs.length} indexed Arabic documents. Do not edit by hand.`,
  terms,
};
fs.writeFileSync(path.join(ROOT, 'worker/src/config/common-terms.ar.json'), JSON.stringify(out, null, 1) + '\n');
console.log(`${terms.length} common terms written`);
