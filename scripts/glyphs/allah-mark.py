"""«ﷲ» (U+FDF2) as an SVG path from Amiri's own outline, for the quick-access buttons (add-on 0072-add15).

The letter set as text overflows its well: its ascenders (the alif, the shadda, the dagger alif) rise above the font's
box, so a font size does not keep it inside. This reads the outline from the Amiri file the app already self-hosts
(@fontsource/amiri 5.3.0, Arabic subset, 700), unchanged, and writes web/src/v2/daily/shortcuts/allah-mark.ts: the
path in a y-down space whose origin is the outline's measured top-left, its measured width and height, and its centre
of mass (area centroid). The placement in the well is computed from these in that module (allahPlacement).

Build time only (fontTools, MIT; docs/COMPONENTS.csv):
  python3 -m venv /tmp/ft && /tmp/ft/bin/pip install fonttools
  /tmp/ft/bin/python -I scripts/glyphs/allah-mark.py
"""
import os
import sys

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.statisticsPen import StatisticsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FONT = os.path.join(ROOT, 'web/node_modules/@fontsource/amiri/files/amiri-arabic-700-normal.woff')
OUT = os.path.join(ROOT, 'web/src/v2/daily/shortcuts/allah-mark.ts')


def num(v: float) -> str:
    s = '%.1f' % v
    return s.rstrip('0').rstrip('.') if '.' in s else s


def main() -> None:
    font = TTFont(sys.argv[1] if len(sys.argv) > 1 else FONT)
    name = font.getBestCmap()[0xFDF2]
    glyphs = font.getGlyphSet()
    g = glyphs[name]
    b = BoundsPen(glyphs)
    g.draw(b)
    x0, y0, x1, y1 = b.bounds
    st = StatisticsPen(glyphs)
    g.draw(st)
    pen = SVGPathPen(glyphs, ntos=num)
    # font units, y up, baseline at 0  ->  y down, origin at the outline's top-left
    g.draw(TransformPen(pen, (1, 0, 0, -1, -x0, y1)))
    d = pen.getCommands()
    w, h = x1 - x0, y1 - y0
    mx, my = st.meanX - x0, y1 - st.meanY
    src = f"""// GENERATED by scripts/glyphs/allah-mark.py from @fontsource/amiri 5.3.0 (amiri-arabic-700-normal.woff, glyph
// {name}, {font['head'].unitsPerEm} units to the em; SIL Open Font License 1.1). Do not edit by hand: run the script.
// «ﷲ» (U+FDF2) as Amiri draws it, outline unchanged, in a y-down space whose origin is its measured top-left.

/** The outline's measured width and height, in font units. */
export const ALLAH_BOX = {{ w: {num(w)}, h: {num(h)} }} as const
/** Its centre of mass (the area centroid of the filled outline), from the same top-left, in font units. */
export const ALLAH_MASS = {{ x: {num(mx)}, y: {num(my)} }} as const
export const ALLAH_PATH =
  '{d}'
"""
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(src)
    print(OUT, 'box', num(w), num(h), 'mass', num(mx), num(my), 'path', len(d))


if __name__ == '__main__':
    main()
