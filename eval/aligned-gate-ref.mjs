// Two more alternatives for the aligned-translation gate, on the same 402 judged items (reply 0031-add11):
//   D  a sentence judge WITH a human reference (Kimi K2.6, temperature 0, JSON, reasoning off as in reply 0031-add8):
//      per sentence the Arabic al-Muyassar sentence, its machine translation, and the human translation of the ayah in
//      the same language as a terminology reference. No Arabic ayah text (in add8 the judge compared against the ayah
//      and flagged what al-Muyassar itself adds). Two questions per sentence; the item is held on any "no".
//   E  prevention at generation: the aligned translation regenerated by DeepSeek V4 Flash with the same prompt
//      (worker/src/explain.ts alignedMessages) plus the human translation as a glossary (eval/gate /aligned):
//      E1 with the current settings (reasoning off), E2 with reasoning on. On the 21 failed items and 40 passed ones
//      drawn with a fixed seed. The new outputs are judged blind (shuffled, without the old verdicts) against the
//      original review's criteria, by a reviewer that never saw which items failed.
// References: bn es fr id ms tr ur from data/processed/ayah_translations.jsonl (the translator it records); en and hi
// from QuranEnc (eval/aligned-gate/fetch-refs-en-hi.mjs: english_saheeh 1.1.2, hindi_omari 1.1.5).
// Limits: one call started every PACE_MS (≤ 2 a second, and under the account's 20 a minute), stop at the first rate
// error, stop at BUDGET neurons (136,000 ≈ $1.5). Resumable per method.
//
//   GATE_URL=http://localhost:8795 node eval/aligned-gate-ref.mjs D E1 E2
//   node eval/aligned-gate-ref.mjs blind     → the shuffled judging file (scratchpad) for the blind reviewer
//   node eval/aligned-gate-ref.mjs report    → ALTERNATIVES.md section, no model call
