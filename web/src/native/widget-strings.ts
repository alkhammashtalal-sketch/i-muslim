// The iOS widgets' texts (reply 0046), in the app's ten languages: Arabic and English reviewed, the others machine
// translation like the rest of the interface. The app writes them with the data (web/src/native/widget-data.ts), so the
// widgets and their gallery speak the app's language. The arrow follows the reading direction.
import type { Lang } from '../../../shared/api'

export type WidgetKind = 'next' | 'times' | 'date' | 'ayah' | 'hadith' | 'tasbih' | 'adhkar' | 'mawaqif' | 'name' | 'salaf' | ControlKind
/** The iOS 18 controls (add-ons 0072-add18 §3.2, 0072-add19 §2) and Android's Quick Settings tile «سبّح» (ctlCount). */
export type ControlKind = 'ctlCount' | 'ctlTasbih' | 'ctlAdhkar' | 'ctlQibla'
export type WidgetStrings = {
  nextPrayer: string
  remaining: string
  after: string
  ayahOfDay: string
  hadithOfDay: string
  tasbih: string
  adhkarNow: string
  cont: string
  openApp: string
  noPlace: string
  readAyah: string
  midnight: string
  lastThird: string
  morning: string
  evening: string
  of: string
  /** The last button of «أذكار المواقف» (reply 0051): the grid of every situation. */
  allAdhkar: string
  /** Add-on 0072-add10: «اسم الله لليوم», its «التالي» (the next page, in the widget), «شارك» (the share image), and
   *  the line after «القراءة» cut at its last whole sentence. */
  nameOfDay: string
  nextPage: string
  share: string
  continueInApp: string
  /** Add-on 0072-add59: the line under each prayer's name in the large times widget and on the times page (sunan.ts):
   *  the sunnah before, the fard and the sunnah after, {n} the rak'ahs in the language's digits; `spoken` the same in
   *  words for VoiceOver and TalkBack, joined by `comma` after the name and the time; `title` and `sources` the times
   *  page's line to the sources (docs/SUNAN.md), `fatwa` its sheet's row for Ibn Baz's fatwa 1432.
   *  Arabic and English reviewed, the eight others machine translation. */
  sunan: SunanStrings
  names: Record<WidgetKind, { name: string; desc: string }>
}
export type SunanStrings = {
  before: string
  fard: string
  after: string
  comma: string
  spoken: { before: Record<2 | 4, string>; fard: Record<2 | 3 | 4, string>; after: Record<2, string> }
  title: string
  sources: string
  /** The fatwa's row in the sheet of sources: the sheikh and its number ({n}, the language's digits), not its title. */
  fatwa: string
}

